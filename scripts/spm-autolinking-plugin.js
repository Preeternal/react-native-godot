const fs = require('node:fs');
const path = require('node:path');
const { resolvePrebuiltConfig } = require('./prebuilt-config');

const packageRoot = path.resolve(__dirname, '..');

module.exports = function godotSpmAutolinkingPlugin(context) {
  const selection = resolvePrebuiltConfig(context.appRoot);
  const iosRoot =
    context.autolinking?.project?.ios?.sourceDir ||
    path.join(context.appRoot, 'ios');
  const manifestRoot = path.join(
    context.outputDir,
    'plugins',
    'ReactNativeGodot'
  );
  const relative = (target) =>
    JSON.stringify(
      path.relative(manifestRoot, target).split(path.sep).join('/')
    );
  let manifest = fs.readFileSync(
    path.join(packageRoot, 'Package.swift'),
    'utf8'
  );
  manifest = manifest.replace(
    '// swift-tools-version: 6.0',
    '// swift-tools-version: 6.0\n// Generated by @preeternal/react-native-godot; do not edit.'
  );
  manifest = manifest.replace(
    /let libGodotVersion = .*\nlet libGodotBaseURL = .*\n/,
    ''
  );
  manifest = manifest.replace(/path: "cpp"/g, 'path: "root/cpp"');
  manifest = manifest.replace(/path: "ios"/g, 'path: "root/ios"');

  for (const [target, name] of [
    ['LibGodot', 'libgodot'],
    ['LibGodotCpp', 'libgodot-cpp'],
  ]) {
    const entry = selection.prebuiltFiles.find((item) => item.name === name);
    manifest = manifest.replace(
      new RegExp(
        `\\.binaryTarget\\(\\s*name: "${target}",[\\s\\S]*?\\n    \\)`
      ),
      `.binaryTarget(\n      name: "${target}",\n      url: "${entry.base_url}${entry.version}/${entry.filename}",\n      checksum: "${entry.shasum}"\n    )`
    );
  }

  // Plugin packages live deeper than ordinary autolinked packages. Resolve all
  // local dependencies from the generated manifest, not the package template.
  const react = context.react?.packageRef;
  const reactDependency = react?.url
    ? `.package(name: "${react.name}", url: "${react.url}", exact: "${react.version}")`
    : `.package(name: "ReactNative", path: ${relative(react?.path || path.join(iosRoot, 'build', 'xcframeworks'))})`;
  manifest = manifest.replace(
    /\.package\(name: "ReactNative", path: "[^"]+"\)/,
    reactDependency
  );
  manifest = manifest.replace(
    /\.package\(name: "React-GeneratedCode", path: "[^"]+"\)/,
    `.package(name: "React-GeneratedCode", path: ${relative(path.join(iosRoot, 'build', 'generated', 'ios'))})`
  );
  manifest = manifest.replace(
    /\.package\(name: "RNWorklets", path: "[^"]+"\)/,
    `.package(name: "RNWorklets", path: ${relative(path.join(context.outputDir, 'libs', 'RNWorklets'))})`
  );

  fs.mkdirSync(manifestRoot, { recursive: true });
  const rootLink = path.join(manifestRoot, 'root');
  fs.rmSync(rootLink, { force: true });
  fs.symlinkSync(packageRoot, rootLink, 'dir');
  fs.writeFileSync(path.join(manifestRoot, 'Package.swift'), manifest);

  return {
    packageDependencies: [{ name: 'ReactNativeGodot', path: manifestRoot }],
    productDependencies: [
      { name: 'ReactNativeGodot', package: 'ReactNativeGodot' },
    ],
    watchPaths: [
      path.join(packageRoot, 'Package.swift'),
      path.join(packageRoot, 'package.json'),
      path.join(packageRoot, 'scripts', 'prebuilt-config.js'),
      path.join(packageRoot, 'scripts', 'spm-autolinking-plugin.js'),
      ...(selection.appPackagePath ? [selection.appPackagePath] : []),
    ],
  };
};
